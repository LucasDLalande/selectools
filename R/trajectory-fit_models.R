#' Fitting non-threshold models
#'
#' Internal function. This function allows to fit non-threshold models based on non-threshold formulas
#' constructed with \code{\link{trajectory_formulas}}. Models are fitted as linear model
#' \code{\link[stats]{lm}} or linear mixed models using \code{\link[lme4]{lmer}}
#' depending on whether random effects are absent or present, respectively.
#' Because the fixed effects structures differ across trajectories, and because we suppose
#' users to provide a priori determined random effects structure, mixed models are
#' fitted by Maximum Likelihood (ML) so \code{REML = FALSE}.
#'
#' @param non_threshold_formulas A \code{list} of object of class \code{formula} representing
#' the non-threshold trajectory formulas or a \code{trajectory.formulas} object generated by
#' \code{\link{trajectory_formulas}}.
#' @param data A \code{data.frame} object containing the variables named in \code{non_threshold_formulas}.
#' @param data_name substitute of \code{data} name.
#' @param random A \code{list} of the random effects present in \code{non_threshold_formulas} obtained by
#' \code{\link[reformulas]{findbars}}.
#' @param lmer_control Advanced users can supply custom optimizer controls for
#' \code{lmerMod} class objects. Defaults to internal object \code{lmerControl_default}
#' which uses Bound Optimization BY Quadratic Approximation, "bobyqa" and 1e5 as
#' maximal number of evaluation.
#'
#' @returns A \code{list} of \code{S3} or \code{S4} objects.
#'
#' @noRd
.fit_non_threshold_models <- function(non_threshold_formulas, data, data_name = data_name, random = NULL, lmer_control) {

  # ---- data ----
  ## create a dedicated environment for model evaluation
  model_env <- new.env(parent = topenv())

  ## assign datasets into this environment
  assign(as.character(data_name)[1], data, envir = model_env)

  # ---- fit lm() ----
  if(is.null(random)) {
    non_threshold_models <- lapply(non_threshold_formulas, function(m) {
      mod <- lm(m, data = data)
      mod$call[[1]] <- quote(stats::lm)
      mod
    })
  }

  # ---- fit lmer() ----
  else {
    non_threshold_models <- lapply(non_threshold_formulas, function(m) {
      mod <- lmer(m, data = data, control = lmer_control, REML = FALSE)
      mod@call[[1]] <- quote(lme4::lmer)
      mod
    })

    non_threshold_models <- lapply(non_threshold_models, function(m) {
      m@call$control <- lmer_control
      m
    })
  }

  # ---- update data name in call ----
  non_threshold_models <- lapply(non_threshold_models, .update_call_data, data_name_symbol = data_name)

  # ---- set evaluation environment ----
  non_threshold_models <- lapply(non_threshold_models, .set_call_env, env = model_env)

  return(non_threshold_models)
}

#' Creating internal dataset for each threshold trajectory with retained threshold value.
#'
#' Internal function. This function internally generates three modified datasets. These
#' datasets are copies of \code{data} generated by \code{.make_modification_data} with
#' \code{var1} and \code{var2} which are copies of \code{trajectory_trait} modified according to
#' the \code{best_threshold} value for each threshold trajectories obtained from
#' \code{\link{estimate_threshold}}. These datasets are used internally for model dredging
#' and can be inspected by the user.
#'
#' @param trajectory_trait A \code{character} string representing the trajectory trait.
#' Must exist in \code{data}.
#' @param data A \code{data.frame} object containing the variables named in \code{non_threshold_formulas}.
#' @param best_thresholds A named \code{list} of \code{numeric} values corresponding to the best
#' threshold value for each threshold trajectory or a \code{threshold.estimation} object
#' generated by \code{\link{estimate_threshold}}. Defaults to \code{NULL}.
#'
#' @return A list of \code{data.frame} objects.
#'
#' @noRd
.make_threshold_dataset <- function(trajectory_trait, data, best_thresholds) {

  # ---- data adjusting functions ----
  adjust_functions <- list(
    thresholdCS = function(data_tmp, var1, var2, trajectory_trait, thr)
      .adjust_data_CS(data_tmp, var1, var2, trajectory_trait, thr),
    thresholdSC = function(data_tmp, var1, var2, trajectory_trait, thr)
      .adjust_data_SC(data_tmp, var1, var2, trajectory_trait, thr),
    thresholdSS = function(data_tmp, var1, var2, trajectory_trait, thr)
      .adjust_data_SS(data_tmp, var1, var2, trajectory_trait, thr)
  )

  datasets_threshold <- list()

  # create alternative data
  vars <- .make_modification_data(trajectory_trait, data)
  var1 <- vars$var1
  var2 <- vars$var2

  for (t in names(best_thresholds)) {

    # reset data variables
    data_tmp <- vars$data2
    data_tmp[[var1]] <- data_tmp[[trajectory_trait]]
    data_tmp[[var2]] <- data_tmp[[trajectory_trait]]

    datasets_threshold[[t]] <- adjust_functions[[t]](data_tmp, var1, var2, trajectory_trait, best_thresholds[[t]])
  }

  return(datasets_threshold)
}

#' Assign environment with threshold datasets to models
#'
#' Internal function. This function allows to assign the top environment with threshold datasets to models.
#'
#' @param datasets_threshold A list of \code{data.frame} object internally generated by \code{.make_threshold_datasets}.
#'
#' @returns An \code{environment} attached to datasets.
#'
#' @noRd
.make_model_env <- function(datasets_threshold) {

  env <- new.env(parent = topenv()) # create an environment whose parent environment is the package environment

  fixed_names <- list(
    thresholdCS = ".data_CS",
    thresholdSC = ".data_SC",
    thresholdSS = ".data_SS"
  )

  for (type in names(datasets_threshold)) {
    assign(fixed_names[[type]], datasets_threshold[[type]], envir = env)
  }

  return(env)
}

#' Fitting threshold models
#'
#' Internal function. This function allows to fit threshold models based on threshold formulas
#' constructed with \code{\link{trajectory_formulas}} and based on estimated thresholds
#' for each threshold trajectory as done by \code{\link{estimate_threshold}}.
#' Models are fitted as linear model \code{\link[stats]{lm}} or linear mixed models
#' using \code{\link[lme4]{lmer}} depending on whether random effects are absent or present, respectively.
#'
#' @param datasets_threshold A list of \code{data.frame} object internally generated by \code{.make_threshold_datasets}.
#' @param data A \code{data.frame} object containing the variables named in \code{non_threshold_formulas}.
#' @param threshold_formulas A \code{list} of object of class \code{formula} representing
#' the threshold trajectory formulas or a \code{trajectory.formulas} object generated by
#' \code{\link{trajectory_formulas}}.
#' @param random A \code{list} of the random effects present in \code{threshold_formulas} obtained by
#' \code{\link[reformulas]{findbars}}.
#' @param lmer_control Advanced users can supply custom optimizer controls for
#' 'lmerMod' class objects. Defaults to internal object \code{lmerControl_default}
#' which uses Bound Optimization BY Quadratic Approximation, "bobyqa" and 1e5 as
#' maximal number of evaluation.
#'
#' @returns A \code{list} of \code{S3} or \code{S4} objects.
#'
#' @noRd
.fit_threshold_models <- function(datasets_threshold, threshold_formulas, random = NULL, lmer_control) {

  model_env <- .make_model_env(datasets_threshold)

  # ---- fit models ----

  threshold_models <- list()

  for (d in names(datasets_threshold)) {

    if (!is.null(random)) {
      threshold_models[[d]] <- lmer(threshold_formulas[[d]], data = datasets_threshold[[d]], control = lmer_control, REML = FALSE)
      threshold_models[[d]]@call$control <- lmer_control
      threshold_models[[d]]@call[[1]] <- quote(lme4::lmer)
    } else {
      threshold_models[[d]] <- lm(threshold_formulas[[d]], data = datasets_threshold[[d]])
      threshold_models[[d]]$call[[1]] <- quote(stats::lm)
    }

      fixed_name <- as.name(switch(d,
                                   thresholdCS = ".data_CS",
                                   thresholdSC = ".data_SC",
                                   thresholdSS = ".data_SS"
      ))

    threshold_models[[d]] <- .update_call_data(threshold_models[[d]], fixed_name)
    threshold_models[[d]] <- .set_call_env(threshold_models[[d]], model_env)
  }

  return(list(
    models = threshold_models,
    env = model_env)
    )
}

#### ---- API functions ---- ####
#' Fitting models
#'
#' This function allows to fit threshold models and non-threshold models based on
#' threshold and non-threshold formulas constructed with \code{\link{trajectory_formulas}}.
#' Threshold models are fitted with generated datasets where the trajectory trait
#' is recalculated based on estimated thresholds as done by \code{\link{estimate_threshold}}.
#' Models are fitted as linear model \code{\link[stats]{lm}} or linear mixed models
#' using \code{\link[lme4]{lmer}} depending on whether random effects are absent or present, respectively.

#'
#' @param formulas A \code{list} of object of class \code{formula} representing trajectory formulas
#' or an object of class \code{trajectory.formulas} created by \code{\link{trajectory_formulas}}.
#' @param trajectory_trait A \code{character} string representing the trajectory trait.
#' Must exist in \code{data}.
#' @param data A \code{data.frame} object containing the variables in \code{formulas}
#' and \code{trajectory_trait}.
#' @param best_thresholds A named \code{list} of \code{numeric} values corresponding to the best
#' threshold value for each threshold trajectory or a \code{threshold.estimation} object
#' generated by \code{\link{estimate_threshold}}. Defaults to \code{NULL}.
#' @param lmer_control Advanced users can supply custom optimizer controls for
#' 'lmerMod' class objects. Defaults to internal object \code{lmerControl_default}
#' which uses Bound Optimization BY Quadratic Approximation, "bobyqa" and 1e5 as
#' maximal number of evaluation.
#'
#' @return An object of class \code{models} containing:
#' \describe{
#'    \item{trajectory_trait}{A \code{character} string representing the trajectory trait.}
#'    \item{random}{The model random terms.}
#'    \item{data}{The name of the dataset.}
#'    \item{datasets_threshold}{A \code{list} of \code{data.frame} objects for threshold models.}
#'    \item{models}{A \code{list} of \code{S3} or \code{S4} objects representing models fits.}
#'    \item{best_thresholds}{A \code{list} of \code{numeric} values representing the threshold
#'    with the lowest criterion value for each threshold trajectory.}
#'    \item{model_env}{An \code{environment} capturing datasets for models.}
#'    }
#'
#' @export
#'
#' @examples
#' # These examples are wrapped in \donttest{} because fitting models on the simulated
#' # data can produce platform-specific numerical errors (macOS ARM64).
#' \donttest{
#' formulas <- trajectory_formulas(formula = log_onset ~ log_mass + (1|Species),
#'                                 trajectory_trait = "log_afr", interactions = "log_mass",
#'                                 data = senescence,
#'                                 trajectories = c("linear", "quadratic", "thresholdCS"))
#'
#' estimation <- estimate_threshold(data = senescence, threshold_formulas = formulas,
#'                                  trajectory_trait = "log_afr",
#'                                  start = -0.5, end = 5.7, iter = 0.1,
#'                                  rank = "AICc")
#'
#' # Provide an object resulting from trajectory_formulas() and an object resulting
#' # from estimate_threshold() and containing best threshold values
#' res <- fit_models(formulas = formulas,
#'                   trajectory_trait = "log_afr",
#'                   data = senescence,
#'                   best_thresholds = estimation)
#'
#' # Or provide named lists
#' # Names must be chosen from "constant", "linear", "quadratic", "factor",
#' # "thresholdCS", "thresholdSC" and "thresholdSS"
#' formulas <- list(
#'   linear = log_onset ~ log_mass + log_afr + log_mass:log_afr + (1|Species),
#'   quadratic = log_onset ~ log_mass + log_afr + I(log_afr^2) +
#'               log_mass:log_afr + log_mass:I(log_afr^2) + (1|Species),
#'   thresholdCS = log_onset ~ log_mass + log_afr.2 + log_mass:log_afr.2 + (1|Species))
#'
#' estimation <- list(
#'   thresholdCS = 1.4)
#'
#' res <- fit_models(formulas = formulas,
#'                   trajectory_trait = "log_afr",
#'                   data = senescence,
#'                   best_thresholds = estimation)
#' }
fit_models <- function(formulas, trajectory_trait, data, best_thresholds = NULL, lmer_control = NULL) {

  # ---- data ----
  if (missing(data) || is.null(data) || !is.data.frame(data)) {
    stop("data must be provided and must be an existing data.frame")
  }

  ## capture the original data name
  data_name <- substitute(data)

  # ---- formulas ----
  if (!inherits(formulas, "trajectory.formulas")) {
    if (length(formulas) == 0) {
      stop("No valid formulas provided")
    }
  }

  allowed_f <- c("constant", "linear", "quadratic", "factor", "thresholdCS", "thresholdSC", "thresholdSS")

  if (!inherits(formulas, "trajectory.formulas")) {

    if (is.null(names(formulas)) || !all(names(formulas) %in% allowed_f)) {
      stop("Unknown trajectory types in formulas. Names must be from: ", paste(allowed_f, collapse = ", "))
    }

    threshold_formulas <- formulas[names(formulas) %in% c("thresholdCS", "thresholdSC", "thresholdSS")]
    non_threshold_formulas <- formulas[names(formulas) %in% c("constant", "linear", "quadratic", "factor")]

  } else {
    threshold_formulas <- formulas$formulas$threshold_formulas
    non_threshold_formulas <- formulas$formulas$non_threshold_formulas
  }

  if (length(non_threshold_formulas) == 0 && length(threshold_formulas) == 0) {
    stop("No valid formulas provided")
  }

  if (length(non_threshold_formulas) > 0) {
    if (!is.list(non_threshold_formulas) || !all(vapply(non_threshold_formulas, function(x) inherits(x, "formula"), logical(1)))) {
      stop("non_threshold_formulas must be a list of formula objects")
    }

    if (!all(vapply(non_threshold_formulas, function(f)
      length(f) == 3,
      logical(1)
    ))) {
      stop("non_threshold_formulas must be a list of two-sided formulas")
    }
  }

  if (length(threshold_formulas) > 0) {
    if (!is.list(threshold_formulas) || !all(vapply(threshold_formulas, function(x) inherits(x, "formula"), logical(1)))) {
      stop("threshold_formulas must be a list of formula objects")
    }

    if (!all(vapply(threshold_formulas, function(f)
      length(f) == 3,
      logical(1)
    ))) {
      stop("threshold_formulas must be a list of two-sided formulas")
    }
  }

  types <- vapply(c(non_threshold_formulas, threshold_formulas), function(f) {
    attr(f, "trajectory_type") %||% NA_character_
  }, FUN.VALUE = character(1))

  if (any(is.na(types) | types == "")) {
    warning("Some formulas were not generated by trajectory_formulas(). Unexpected behaviors can be expected.")
  }

  # ---- trajectory_trait ----
  if (!is.character(trajectory_trait) || length(trajectory_trait) != 1) {
    stop("trajectory_trait must be a single character string")
  }

  if (!trajectory_trait %in% names(data)) {
    stop("trajectory_trait must be a variable of 'data'")
  }

  # ---- best_thresholds ----
  allowed_bt <- c("thresholdCS", "thresholdSC", "thresholdSS")

  ## check whether best_thresholds is required
  if (length(threshold_formulas) > 0) {
    if (is.null(best_thresholds)) {
      stop("best_thresholds must be provided when threshold models are included")
    }

    if (!inherits(best_thresholds, "threshold.estimation")) {
      if (is.null(names(best_thresholds)) || !all(names(best_thresholds) %in% allowed_bt)) {
        stop("Unknown threshold types in best_thresholds. Names must be from: ", paste(allowed_bt, collapse =", "))
      }

      best_thresholds <- best_thresholds[names(best_thresholds) %in% allowed_bt]

    } else {
      best_thresholds <- best_thresholds$best_thresholds
    }

    if (!is.list(best_thresholds) || !all(vapply(best_thresholds, is.numeric, logical(1)))) {
      stop("best_thresholds must be a non-empty list of numeric objects")
    }

    types <- vapply(best_thresholds, function(f) {
      attr(f, "best_threshold") %||% NA_character_
    }, FUN.VALUE = character(1))

    if (any(is.na(types) | types == "")) {
      warning("Some threshold estimations were not generated by estimate_threshold(). Unexpected behaviors can be expected.")
    }
  } else {

    if (length(threshold_formulas) == 0 && !is.null(best_thresholds)) {
      warning("best_thresholds ignored because no threshold formulas were provided")
    }

    best_thresholds <- NULL
  }

  if (length(threshold_formulas) > 0) {
    diff_thr <- setdiff(names(threshold_formulas), names(best_thresholds))

    if (length(diff_thr) > 0) {
      stop("Missing threshold values for: ", paste(diff_thr, collapse=", "))
    }
  }

  # ---- random ----
  random <- NULL
  if (length(non_threshold_formulas) > 0) {
    random <- findbars(non_threshold_formulas[[1]])
  } else if (length(threshold_formulas) > 0) {
    random <- findbars(threshold_formulas[[1]])
  }

  if (!is.null(random)) {
    random_txt <- paste0("(", vapply(random, function(x) .collapse_deparse(x), ""), ")", collapse = " + ")
  } else random_txt <- NULL

  # ---- lmer_control ----
  if (!is.null(lmer_control)) {
    if (!inherits(lmer_control, c("lmerControl", "merControl"))) {
      stop("lmer_control must be NULL or a lmerControl, merControl object. See help page for details")
    }
  }

  if (!is.null(random)) {
    if (is.null(lmer_control)) {
      lmer_control <- lmerControl_default
    }
  } else {
    lmer_control <- NULL
  }

  # ---- fit models ----
  non_threshold_models <- .fit_non_threshold_models(non_threshold_formulas, data, data_name = data_name, random, lmer_control)

  if (length(threshold_formulas) > 0) {
    datasets_threshold <- .make_threshold_dataset(trajectory_trait, data, best_thresholds)

    threshold_results <- .fit_threshold_models(datasets_threshold, threshold_formulas, random, lmer_control)
    threshold_models <- threshold_results$models
    model_env <- threshold_results$env

  } else {
    datasets_threshold <- NULL
    threshold_models <- list()
    model_env <- new.env(parent = topenv())
  }

  assign(as.character(data_name), data, envir = model_env)

  # ---- combine models ----
  all_models <- c(non_threshold_models, threshold_models)

  models <- list(
    trajectory_trait = trajectory_trait,
    random = random_txt,
    data = data_name,
    datasets_threshold = datasets_threshold,
    models = all_models,
    best_thresholds = best_thresholds,
    model_env = model_env
  )

  class(models) <- "models"

  return(models)
}

#### ---- S3 Method ---- ####
#' Print models
#'
#' Displays a readable summary of the trajectory models fitted by \code{\link{fit_models}}.
#'
#' @param x An object of class \code{models}.
#' @param ... Further arguments (currently unused).
#'
#' @return Invisibly returns \code{x}.
#'
#' @method print models
#' @seealso \code{\link{fit_models}}
#'
#' @export
print.models <- function(x, ...) {
  .title_box("MODELS FITTED")
  cat("Trajectories based on trait:", x$trajectory_trait, "\n")
  cat("Random term(s):", ifelse(is.null(x$random), "None", x$random), "\n")
  cat("Dataset:", x$data, "\n")
  if (!is.null(x$datasets_threshold)) {
    cat("\nFor threshold model(s), the following dataset(s) have been generated and used:\n")
    for (n in names(x$datasets_threshold)) {
      cat(paste0("-  x$datasets_threshold$", n), "with threshold:", x$best_thresholds[[n]], "\n")
    }
    cat("\nThese datasets are copies of original data with trajectory trait variables adapted to threshold trajectories.\n")
  }
  cat("\n")

  .sep_line()

  cat("To consult summaries of models fitted please use:\n")
  for (n in names(x$models)) {
    cat(paste0("summary(x$models$", n), ")\n", sep="")
  }
  cat("\n")

  .sep_line()

  return(invisible(x))
}

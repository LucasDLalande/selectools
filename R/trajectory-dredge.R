#' Print best trajectories
#'
#' Displays a readable overview of the trajectories dredging returned by \code{\link{dredge_trajectories}}
#' and treated by \code{\link{best_trajectory}}.
#'
#' @param x An object of class \code{best.trajectory}.
#' @param type A \code{character} string to choose whether to display information about the
#' final trajectory (\code{"global"}, default) or about the best models of each trajectory
#' (\code{"by_trajectory"}).
#' @param ... Further arguments (currently unused).
#'
#' @return Invisibly returns \code{x}.
#'
#' @method print best.trajectory
#' @seealso \code{\link{best_trajectory}}
#'
#' @export
print.best.trajectory <- function(x, type = c("global", "by_trajectory"), ...) {

  type <- match.arg(type)

  if (type == "global") {

    .title_box(paste0("BEST TRAJECTORY: ", .first_upp(x$final_traj_name)))
    cat("RECAP:\n")
    print(x$final_traj)
    cat("\n\nRETAINED MODEL:\n")
    for (n in x$final_traj$trajectory) {
      cat(.first_upp(n), "\n")
      print(x$final_summary[[n]]$call$formula)
    }

  } else {
    .title_box("TRAJECTORIES RECAP")
    cat("RECAP TABLE:\n")
    print(x$best_table)
    cat("\n\nRETAINED MODELS:\n\n")
    for (n in x$best_table$trajectory) {
      cat(.first_upp(n), "\n")
      print(x$summaries[[n]]$call$formula)
      cat("\n")
    }
  }
}

#' Print best trajectories
#'
#' Displays a readable overview of the trajectories dredging returned by \code{\link{dredge_trajectories}}
#' and treated by \code{\link{best_trajectory}} and the summaries of retained trajectories.
#'
#' @param object An object of class \code{best.trajectory}.
#' @param type A \code{character} string to choose whether to display information about the
#' final trajectory (\code{"global"}, default) or about the best models of each trajectory
#' (\code{"by_trajectory"}).
#' @param ... Further arguments (currently unused).
#'
#' @return Invisibly returns \code{x}.
#'
#' @method summary best.trajectory
#' @seealso \code{\link{best_trajectory}}
#'
#' @export
summary.best.trajectory <- function(object, type = c("global", "by_trajectory"), ...) {

  # ---- Common part: trajectory recap ----
  print(object, type = type)

  # ---- Summaries ----
  type <- match.arg(type)

  trajectories <- if (type == "global") object$final_traj$trajectory else object$best_table$trajectory

  for (n in trajectories) {
    .title_box(paste0("TRAJECTORY SUMMARY: ", .first_upp(n)))

    if (type == "global") print(object$final_summary[[n]]) else print(object$summaries[[n]])
  }

  cat("\n")
  .sep_line()
}

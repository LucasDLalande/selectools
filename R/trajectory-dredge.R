#' Dredging all trajectories
#'
#' This function applies the \code{\link[MuMIn]{dredge}} function to each model trajectory.
#' For each trajectory (constant, linear, quadratic, factor, thresholds), the function
#' selects the best model based on criterion (AIC or AICc) value. The best model
#' is defined as the simplest model (i.e. lowest degrees of freedom, df) within
#' a delta criterion value chosen by the user. For each trajectory, the full
#' dredge table is generated and can be consulted, as well as the table of models
#' ranked within the delta criterion value chosen, and the retained model for
#' each trajectory.
#' For each trajectory, the trajectory trait is fixed, so that only other covariables
#' and interactions between the trajectory trait and covariables are evaluated.
#' Reminder: Because the fixed effects structures differ across trajectories, and because we suppose
#' users to provide a priori determined random effects structure, mixed models are
#' fitted by Maximum Likelihood (ML) so \code{REML = FALSE}.
#' Note: Some convergence warnings may appear during model dredging and do not
#' necessarily indicate model misspecification.
#'
#' @param models A \code{list} of \code{lm} or \code{lmerMod} objects from the
#' \code{models} class object generated by \code{\link{fit_models}}.
#' @param trajectory_trait A \code{character} string representing the trajectory trait.
#' Must exist in \code{data}.
#' @param rank Criterion used to rank the models. Choose either \code{"AIC"} or \code{"AICc"}.
#' @param delta_criterion A numeric value to define the criterion value within which
#' the best model is selected. Defaults to \code{2}.
#' @param data A \code{data.frame} object containing the variables named in \code{models}
#' and \code{trajectory_trait}.
#'
#' @return An object of class \code{dredge.results} containing:
#' \describe{
#'    \item{full_table}{A \code{list} of \code{model.selection} objects (one per trajectory)
#'    displaying the results from \code{\link[MuMIn]{dredge}}.}
#'    \item{all_under_delta}{A \code{list} of \code{data.frame} (one per trajectory) displaying
#'    a subset of the results from \code{\link[MuMIn]{dredge}}. Only models below
#'    \code{delta_criterion} are displayed.}
#'    \item{min_df}{A \code{list} of \code{data.frame} (one per trajectory) displaying a subset
#'    of the results from \code{\link[MuMIn]{dredge}}. Only models with the lowest number
#'    of parameters (df) below \code{delta_criterion} are displayed.}
#'    \item{best_models}{A \code{list} of \code{data.frame} (one per trajectory) displaying a
#'    subset of the results from \code{\link[MuMIn]{dredge}}. Only the best model
#'    (i.e. having both the lowest rank value and number of parameters) is displayed.}
#'    \item{rank}{The criterion used to rank the models.}
#'    \item{model_env}{An \code{environment} capturing datasets for threshold models.}
#'    }
#'
#' @export
#'
#' @examples
#' # These examples are wrapped in \donttest{} because fitting models on the simulated
#' # data can produce platform-specific numerical errors (macOS ARM64).
#' \donttest{
#' formulas <- trajectory_formulas(formula = log_onset ~ log_mass + (1|Species),
#'                                 trajectory_trait = "log_afr", interactions = "log_mass",
#'                                 data = senescence,
#'                                 trajectories = c("linear", "quadratic", "thresholdCS"))
#'
#' estimation <- estimate_threshold(data = senescence, threshold_formulas = formulas,
#'                                  trajectory_trait = "log_afr",
#'                                  start = -0.5, end = 5.7, iter = 0.1,
#'                                  rank = "AICc")
#'
#' fit <- fit_models(formulas = formulas,
#'                   trajectory_trait = "log_afr",
#'                   data = senescence,
#'                   best_thresholds = estimation)
#'
#' # Provide an object resulting from fit_models()
#' res <- dredge_trajectories(models = fit,
#'                            trajectory_trait = "log_afr",
#'                            rank = "AICc",
#'                            delta_criterion = 2,
#'                            data = senescence)
#' }
dredge_trajectories <- function(models, trajectory_trait, rank = c("AIC", "AICc"), delta_criterion = 2, data) {

  # ---- data ----
  if (missing(data) || is.null(data) || !is.data.frame(data)) {
    stop("data must be provided and must be an existing data.frame")
  }

  # ---- models ----
  if (!inherits(models, "models")) {
    stop("models must be a list of 'models' class objects returned by fit_models()")
  }

  datasets_threshold <- models$datasets_threshold
  all_models <- models$models

  for (i in seq_along(all_models)) {
    if (inherits(all_models[[i]], "lmerMod")) {
      all_models[[i]]@call$control <- NULL
    } else if (inherits(all_models[[i]], "lm")) {
      all_models[[i]]$call$control <- NULL
    }
  }

  # ---- model environment ----
  ## temporarily attach model_env to search path during dredge
  model_env <- models$model_env
  if (!is.null(model_env)) {
    # clean potential previous residual attachments from previous calls
    while (".trajectory_model_env" %in% search()) {
      detach(".trajectory_model_env")
    }

    ### Because MuMIn::dredge() evaluates formulas by searching objects in data, .GlobalEnv or attached environments,
    ### here, we require to attach the environment with an attach call
    ### Following Good Practice in ?attach, we use a distinctive name argument and
    ### immediately follow the attach call by an on.exit call to detach the distinctive name
    attach(model_env, name = ".trajectory_model_env", warn.conflicts = FALSE)
    on.exit(
      if (".trajectory_model_env" %in% search()) detach(".trajectory_model_env"),
      add = TRUE
    )
  }

  # ---- trajectory_trait ----
  if (!is.character(trajectory_trait) || length(trajectory_trait) != 1) {
    stop("trajectory_trait must be a single character string")
  }

  if (!trajectory_trait %in% names(data)) {
    stop("trajectory_trait must be a variable of 'data'")
  }

  # ---- delta_criterion ----
  if (!is.numeric(delta_criterion) || length(delta_criterion) != 1 || is.na(delta_criterion) || delta_criterion < 0) {
    stop("delta_criterion must be a single non-negative numeric value")
  }

  # ---- rank ----
  rank <- match.arg(rank)

  # ---- fixed terms ----
  fixed_terms <- list(
    constant = ~1,
    linear = as.formula(paste("~", trajectory_trait)),
    quadratic = as.formula(paste("~", trajectory_trait, "+ I(", trajectory_trait, "^2)")),
    factor = as.formula(paste("~factor(", trajectory_trait, ")")),
    thresholdCS = as.formula(paste("~", paste0(trajectory_trait, ".2"))),
    thresholdSC = as.formula(paste("~", paste0(trajectory_trait, ".1"))),
    thresholdSS = as.formula(paste("~", paste(c(paste0(trajectory_trait, ".1"), paste0(trajectory_trait, ".2")), collapse = " + ")))
  )

  fixed_terms <- fixed_terms[names(all_models)]
  fixed_terms <- fixed_terms[!vapply(fixed_terms, is.null, logical(1))]
  all_models <- all_models[names(fixed_terms)]

  # ---- dredging ----
  full_dredge <- list()

  for (d in names(all_models)) {
    message("Dredge is running for: ", d,
            " trajectory\nFixed term(s): (Intercept), ",
            deparse(fixed_terms[[d]][[2]])
            )

    full_dredge[d] <- list(
      tryCatch({

        with_options(
        list(na.action = "na.fail"),
        suppressMessages(
          dredge(all_models[[d]], evaluate = TRUE, rank = rank, trace = 2, fixed = fixed_terms[[d]]))
        )
        }, error = function(e) {

        message("ERROR for ", d, " trajectory: ", conditionMessage(e))
        structure(
          data.frame(), class = c("model.selection", "data.frame")
        )
      })
      )
    }

  # ---- filter dredge output ----
  ## all models under delta_AIC/AICc
  criterion_dredge <- lapply(full_dredge, function(d) {

    if (is.null(d) || nrow(d) == 0) {
      warning("No models for at least a trajectory")
      return(NULL)
    }

    out <- subset(d, delta <= delta_criterion, recalc.weights = FALSE)

    if (nrow(out) == 0) {
      warning(paste0("No models <= ", delta_criterion, " ", rank, " for at least a trajectory."))
      return(NULL)
    }

    return(out)
  })

  ## the simplest models under delta_AIC
  df_dredge <- lapply(criterion_dredge, function(d) {
    subset(d, which(df == min(df)), recalc.weights = FALSE)
  })

  ## the model with the lowest AIC(c) among simplest models
  best_dredge <- lapply(df_dredge, function(d) {
    subset(d, which(rank == min(rank)), recalc.weights = FALSE)
  })

  for (d in names(all_models)) {
    if (!is.null(best_dredge[[d]]) && nrow(best_dredge[[d]]) > 1) {
      message("Several models with similar number of parameters and ", rank, " values were found for trajectory: ",
              paste(d, collapse = ", "))
    }
  }

  dredge_results <- list(
    full_table = full_dredge,
    all_under_delta = criterion_dredge,
    min_df = df_dredge,
    best_models = best_dredge,
    rank = rank,
    model_env = model_env
  )

  class(dredge_results) <- "dredge.results"

  return(dredge_results)
}

#' Selecting the final trajectory model
#'
#' The best model for each trajectory obtained by \code{\link{dredge_trajectories}}
#' are compared between them based on their criterion (AIC or AICc) value and
#' number of parameters (df). As suggested by some methods it is possible to
#' add 1 df and 2 AIC/AICc points to account for the implicit cost of the threshold
#' parameter by setting the \code{adjust_threshold} argument to \code{TRUE} (default).
#' Note: For each threshold models, the function add 1 number of parameter and 2 AIC or AICc points
#' to the final df and criterion value to account for the cost of the implicit
#' parameter that is the threshold.
#'
#' @param dredge_results A \code{list} of \code{model.selection} object from the \code{dredge.results}
#' class object generated by \code{\link{dredge_trajectories}}.
#' @param delta_criterion A \code{numeric} value to define the criterion value within which
#' the best model is selected. Defaults to \code{2}.
#' @param adjust_threshold Logical. If \code{TRUE} (default), adds 1 parameter (df) and
#' 2 AIC/AICc points to threshold models to account for the implicit cost of the
#' threshold parameter as suggested by some methods.
#'
#' @export
#'
#' @return An object of class \code{best.trajectory} containing:
#' \describe{
#'    \item{best_table}{A \code{data.frame} displaying the rank, number of parameters
#'    and delta rank value for the best model of each trajectory.}
#'    \item{final_traj}{A \code{data.frame} displaying the rank, number of parameters
#'    and delta rank value for the best model across all trajectories and according
#'    to the \code{delta_criterion} argument.}
#'    \item{final_traj_name}{A \code{character} string for the name of the final trajectory.}
#'    \item{summaries}{A \code{list} of \code{summary.merMod} objects (one per trajectory).}
#'    \item{summary}{A \code{list} of \code{summary.merMod} object for the final trajectory.}
#'    }
#'
#' @examples
#' # These examples are wrapped in \donttest{} because fitting models on the simulated
#' # data can produce platform-specific numerical errors (macOS ARM64).
#' \donttest{
#' formulas <- trajectory_formulas(formula = log_onset ~ log_mass + (1|Species),
#'                                 trajectory_trait = "log_afr", interactions = "log_mass",
#'                                 data = senescence,
#'                                 trajectories = c("linear", "quadratic", "thresholdCS"))
#'
#' estimation <- estimate_threshold(data = senescence, threshold_formulas = formulas,
#'                                  trajectory_trait = "log_afr",
#'                                  start = -0.5, end = 5.7, iter = 0.1,
#'                                  rank = "AICc")
#'
#' fit <- fit_models(formulas = formulas,
#'                   trajectory_trait = "log_afr",
#'                   data = senescence,
#'                   best_thresholds = estimation)
#'
#' # Provide an object resulting from fit_models()
#' dredge_results <- dredge_trajectories(models = fit,
#'                                       trajectory_trait = "log_afr",
#'                                       rank = "AICc",
#'                                       delta_criterion = 2,
#'                                       data = senescence)
#'
#' # Provide a dredge.results object resulting from dredge_trajectories()
#' res <- best_trajectory(dredge_results,
#'                        delta_criterion = 2,
#'                        adjust_threshold = TRUE)
#' }
best_trajectory <- function(dredge_results, delta_criterion, adjust_threshold = TRUE) {

  # ---- dredge_results ----
  if (!inherits(dredge_results, "dredge.results")) {
    stop("dredge_results must be a list of 'dredge.results' class objects returned by dredge_trajectories()")
  }

  best_models <- dredge_results$best_models
  rank <- dredge_results$rank

  # ---- model environment ----
  ## temporarily attach model_env to search path during dredge
  model_env <- dredge_results$model_env
  if (!is.null(model_env)) {
    attach(model_env, name = ".trajectory_model_env", warn.conflicts = FALSE)
    on.exit(
      if (".trajectory_model_env" %in% search()) detach(".trajectory_model_env"),
      add = TRUE
    )
  }

  # ---- delta_criterion ----
  if (!is.numeric(delta_criterion) || length(delta_criterion) != 1 || is.na(delta_criterion) || delta_criterion < 0) {
    stop("delta_criterion must be a single non-negative numeric value")
  }

  # ---- Trajectory ----
  ## best_table: best models for all trajectories
  best_table <- data.frame()

  ### constructs best_table
  for (i in seq_along(best_models)) {
    best_table[i, "trajectory"] <- names(best_models[i])
    best_table[i, "df"] <- best_models[[i]]$df
    best_table[i, rank] <- best_models[[i]]$rank
  }

  ### df and rank adjustment
  if (adjust_threshold) {
    message("********************************************************************************
Note: For threshold models, df is incremented by 1 and ", rank, " by 2 to account for
the implicit threshold parameter.
********************************************************************************")

    best_table$df <- ifelse(grepl("threshold", best_table$trajectory), best_table$df + 1, best_table$df)
    best_table[[rank]] <- ifelse(grepl("threshold", best_table$trajectory), best_table[[rank]] + 2, best_table[[rank]])
  }

  ### delta rank
  best_table$delta <- best_table[, rank] - min(best_table[, rank])

  ## Final trajectory
  final_traj <- best_table[best_table$delta <= delta_criterion, ]
  final_traj <- final_traj[which(final_traj$df == min(final_traj$df, na.rm = TRUE)),]

  ### if several have the same df
  if (nrow(final_traj) > 1) {
    final_traj <- final_traj[which(final_traj$delta == min(final_traj$delta, na.rm = TRUE)),]

  ### if several have the same df and rank
    if (nrow(final_traj) > 1) {
      message("Some trajectories have similar number of parameters and AICc values have been found: ", paste(final_traj$trajectory, collapse = ", "))
    }
  }

  ### name(s) of the final trajectory/trajectories
  for (r in 1:nrow(final_traj)) {
    final_traj_name <- paste(final_traj$trajectory[r], collapse = ", ")
  }

  # ---- Summaries ----
  ## summaries of all final trajectory models
  summaries <- list()

  for (n in names(best_models)) {
    summaries[[n]] <- summary(get.models(best_models[[n]], subset = 1)[[1]])
  }

  ## summary of the final trajectory/trajectories
  final_summary <- list()

  for (n in final_traj$trajectory) {
    final_summary[[n]] <- summary(get.models(best_models[[n]], subset = 1)[[1]])
  }

  message("\nTrajectories recap and models summaries can be consulted using:
print(x, type = c('global', 'by_trajectory'))
summary(x, type = c('global', 'by_trajectory'))")

  best_trajectory <- list(
    best_table = best_table,
    final_traj = final_traj,
    final_traj_name = final_traj_name,
    summaries = summaries,
    final_summary = final_summary
  )

  class(best_trajectory) <- "best.trajectory"

  return(best_trajectory)
}


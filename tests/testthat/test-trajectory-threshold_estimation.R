#### Test .adjust_data_*() ####
## correct results
test_that(".adjust_data_* correctly calculate var1 and var2", {
  # small sample size to facilitate calculation of expected values
  df <- data.frame(y = 1:5, x = 1:5)

  modif_data <- .make_modification_data(trajectory_trait = "x", data = df)
  df2 <- modif_data$data2

  # create a temporary data to be modified
  df_tmp_CS <- df2
  df_tmp_SC <- df2
  df_tmp_SS <- df2

  thr <- 3

  res_CS <- .adjust_data_CS(data_tmp = df_tmp_CS, var1 = "x.1", var2 = "x.2", trajectory_trait = "x", thr = thr)
  res_SC <- .adjust_data_SC(data_tmp = df_tmp_SC, var1 = "x.1", var2 = "x.2", trajectory_trait = "x", thr = thr)
